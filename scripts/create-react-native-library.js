#!/usr/bin/env node
/**
 * create-react-native-library.js
 * Generates a library with create-react-native-library, packs it,
 * and adds the packed library to the app in the current directory
 *
 * Usage:
 *   node scripts/create-react-native-library.js <create-react-native-library options>
 */

const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const args = process.argv.slice(2);

if (args.length === 0) {
  console.error(
    'Usage: node scripts/create-react-native-library.js <create-react-native-library options>'
  );
  console.error(
    'Example: node scripts/create-react-native-library.js --type turbo-module --languages kotlin-objc'
  );
  process.exit(1);
}

const appDir = process.cwd();

// A new directory on each run, so retries don't reuse a partially created library
const tempDir = fs.mkdtempSync(
  path.join(os.tmpdir(), 'create-react-native-library-')
);
const libraryDir = path.join(tempDir, 'react-native-test-library');

execFileSync(
  'npx',
  [
    'create-react-native-library@latest',
    ...args,
    '--yes',
    '--directory',
    libraryDir,
    '--slug',
    'react-native-test-library',
    '--description',
    'Library generated by create-react-native-library',
    '--author-name',
    'React Native Community',
    '--author-email',
    'nightly-tests@example.com',
    '--author-url',
    'https://github.com/react-native-community',
    '--repo-url',
    'https://github.com/react-native-community/nightly-tests',
    '--example',
    'vanilla',
  ],
  { cwd: tempDir, stdio: 'inherit' }
);

// The CLI doesn't allow skipping the example app,
// but only the packed library is tested in the nightly app.
fs.rmSync(path.join(libraryDir, 'example'), { recursive: true });

execFileSync('yarn', ['install'], {
  cwd: libraryDir,
  stdio: 'inherit',
  env: {
    ...process.env,
    // Template dependencies may be published on the same day,
    // and Yarn rejects them by default due to the minimal age gate.
    YARN_NPM_MINIMAL_AGE_GATE: '0',
    // The generated library has no lockfile, and Yarn forbids
    // creating one on CI by default due to immutable installs.
    YARN_ENABLE_IMMUTABLE_INSTALLS: 'false',
  },
});

execFileSync('npm', ['pack', '--pack-destination', tempDir], {
  cwd: libraryDir,
  stdio: 'inherit',
});

const pkg = JSON.parse(
  fs.readFileSync(path.join(libraryDir, 'package.json'), 'utf8')
);

// Peer dependencies such as react-native-nitro-modules are needed in the app,
// react and react-native are excluded since the app already has the nightly.
const peerDependencies = Object.entries(pkg.peerDependencies ?? {})
  .filter(([name]) => name !== 'react' && name !== 'react-native')
  .map(([name, version]) => `${name}@${version}`);

execFileSync(
  'yarn',
  [
    'add',
    `file:${path.join(tempDir, `${pkg.name}-${pkg.version}.tgz`)}`,
    ...peerDependencies,
  ],
  { cwd: appDir, stdio: 'inherit' }
);
